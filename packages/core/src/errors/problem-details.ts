import { z } from 'zod';

/**
 * RFC 9457 Problem Details for HTTP APIs (application/problem+json)
 */
export const ProblemDetailsSchema = z.object({
  type: z.string().describe('URI reference identifying the problem type'),
  title: z.string().describe('Short, human-readable summary of the problem type'),
  status: z.number().int().describe('HTTP status code generated by the origin server'),
  detail: z.string().describe('Human-readable explanation specific to this occurrence of the problem'),
  code: z.string().describe('Stable, machine-readable application error code'),
  instance: z.string().optional().describe('URI reference identifying the specific occurrence'),
  invalidParams: z
    .array(
      z.object({
        name: z.string(),
        reason: z.string(),
      })
    )
    .optional()
    .describe('List of invalid parameter errors for 422 Unprocessable Entity'),
  currentEntity: z.unknown().optional().describe('Current state of the entity in 412 Precondition Failed conflicts'),
  details: z.unknown().optional().describe('Additional structured context if safe for consumer'),
});

export type ProblemDetails = z.infer<typeof ProblemDetailsSchema>;

export interface CreateProblemDetailsOptions {
  type?: string;
  title: string;
  status: number;
  detail: string;
  code: string;
  instance?: string;
  invalidParams?: Array<{ name: string; reason: string }>;
  currentEntity?: unknown;
  details?: unknown;
}

export function createProblemDetails(options: CreateProblemDetailsOptions): ProblemDetails {
  const typeUri =
    options.type ||
    `https://api.workspace.dev/errors/${options.code.toLowerCase().replace(/_/g, '-')}`;

  const payload: ProblemDetails = {
    type: typeUri,
    title: options.title,
    status: options.status,
    detail: options.detail,
    code: options.code,
  };

  if (options.instance) {
    payload.instance = options.instance;
  }

  if (options.invalidParams && options.invalidParams.length > 0) {
    payload.invalidParams = options.invalidParams;
  }

  if (options.currentEntity !== undefined) {
    payload.currentEntity = options.currentEntity;
  }

  if (options.details !== undefined) {
    payload.details = options.details;
  }

  return payload;
}
